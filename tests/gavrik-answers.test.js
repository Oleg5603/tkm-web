const assert=require('node:assert/strict');
const gavrik=require('../assets/gavrik.js');

const cases=[
  ['Какие основные принципы ТКМ?','традиционная система'],
  ['Что такое Инь и Ян?','взаимосвязанные противоположности'],
  ['Объясни У-син и пять элементов','пять фаз'],
  ['Что такое Ци?','функциональное понятие'],
  ['Что такое Цзан-Фу?','функциональных систем'],
  ['Назови восемь принципов','внутреннее/внешнее'],
  ['Как работает правило мать-сын?','цикле порождения'],
  ['Что такое полдень-полночь?','суточном цикле'],
  ['Что такое меридиан?','не следует отождествлять с сосудами'],
  ['Работает ли ТКМ научно?','доказательность'],
  ['Можно ли подобрать китайские травы?','взаимодействовать с лекарствами'],
  ['У меня резкая боль и одышка','срочной медицинской помощью'],
  ['Не могу уснуть','Нарушения сна'],
  ['Можно ли массировать точку до боли?','не должно вызывать резкую боль'],
  ['Я беременна, можно прогревать точки?','беременности'],
  ['Где рассчитать точки?','Перейдите к разделу'],
  ['Храните ли вы мои данные?','Текст вопроса Гаврику в аналитику не отправляется']
];

for(const [question,expected] of cases)assert.match(gavrik.answer(question),new RegExp(expected,'i'),question);
assert.match(gavrik.answer('Инь Ян и пять элементов'),/взаимосвязанные противоположности.*пять фаз/i);
assert.match(gavrik.answer('непонятный вопрос'),/Можно спросить об Инь–Ян/i);
assert.equal(gavrik.answer(''),gavrik.fallback);
assert.ok(gavrik.answers.length>=50,'база Гаврика должна содержать не менее 50 сценариев');
assert.deepEqual(gavrik.respond('Где подобрать точки?').links,[{href:'#picker',label:'Открыть подбор точек'}]);
assert.deepEqual(gavrik.respond('Как пить воду после 50?').links,[{href:'topics.html',label:'Открыть материалы'}]);

console.log(`OK: Gavrik principles=${cases.length}, multi-topic and fallback`);
